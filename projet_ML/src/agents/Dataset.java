    private static final int N_FEATURES = 4;
    private static final int N_CLASSES = 3;

    private double[][] X_train, X_test;
    private int[] y_train, y_test;

    // Bornes de normalisation
    private double[] minVals, maxVals;

    // ------------------------------------------------------------
    // Chargement + train/test split (seed fixe pour reproductibilité)
    // ------------------------------------------------------------
    public void load() {
        int n = IRIS.length;
        int[] indices = new int[n];
        for (int i = 0; i < n; i++) indices[i] = i;

        // Mélange avec seed fixe
        Random rand = new Random(42);
        for (int i = n - 1; i > 0; i--) {
            int j = rand.nextInt(i + 1);
            int tmp = indices[i];
            indices[i] = indices[j];
            indices[j] = tmp;
        }

        // 80% train / 20% test
        int nTrain = (int) (n * 0.8);
        int nTest = n - nTrain;

        X_train = new double[nTrain][N_FEATURES];
        y_train = new int[nTrain];
        X_test = new double[nTest][N_FEATURES];
        y_test = new int[nTest];

        for (int i = 0; i < nTrain; i++) {
            int idx = indices[i];
            for (int j = 0; j < N_FEATURES; j++) X_train[i][j] = IRIS[idx][j];
            y_train[i] = (int) IRIS[idx][N_FEATURES];
        }
        for (int i = 0; i < nTest; i++) {
            int idx = indices[nTrain + i];
            for (int j = 0; j < N_FEATURES; j++) X_test[i][j] = IRIS[idx][j];
            y_test[i] = (int) IRIS[idx][N_FEATURES];
        }

        // Normalisation min-max (calculée sur train uniquement)
        minVals = new double[N_FEATURES];
        maxVals = new double[N_FEATURES];
        for (int j = 0; j < N_FEATURES; j++) {
            minVals[j] = Double.MAX_VALUE;
            maxVals[j] = -Double.MAX_VALUE;
            for (int i = 0; i < nTrain; i++) {
                if (X_train[i][j] < minVals[j]) minVals[j] = X_train[i][j];
                if (X_train[i][j] > maxVals[j]) maxVals[j] = X_train[i][j];
            }
        }
        normalize(X_train);
        normalize(X_test);
    }

    private void normalize(double[][] X) {
        for (int i = 0; i < X.length; i++) {
            for (int j = 0; j < N_FEATURES; j++) {
                double range = maxVals[j] - minVals[j];
                if (range == 0) range = 1;
                X[i][j] = (X[i][j] - minVals[j]) / range;
            }
        }
    }

    public double[][] getX_train() { return X_train; }
    public double[][] getX_test()  { return X_test; }
    public int[] getY_train()      { return y_train; }
    public int[] getY_test()       { return y_test; }
    public static int getNFeatures() { return N_FEATURES; }
    public static int getNClasses()  { return N_CLASSES; }
